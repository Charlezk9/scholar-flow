 ok('不执行原始 HTML',!q('.lit-md script'));
 ok('图占位不向外发请求',!q('.lit-md img')&&text(q('.lit-figure')).includes('图示'));
 ok('KaTeX 定位参数保留', !!q('.katex .strut')?.getAttribute('style'));
 await React.act(async()=>{root.render(React.createElement(MarkdownReader,{fontSize:24,text:'$$\\frac{1}{\\sqrt{d_k}} \\tag{1}$$\n\n:::caption\nFigure 1: 原图注\n:::\n\n:::metadata\n作者机构\n:::\n\n:::note\n原文脚注\n:::\n\n> 原文引用'}));});
