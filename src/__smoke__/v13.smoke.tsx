import { setupDom, section, ok, report, q, qa, text, byText, click, typeInto, pressKey, sleep } from "./harness";
setupDom();
async function main() {
  const React = await import("react");
  const { createRoot } = await import("react-dom/client");
  const { useStore, DEFAULT_SETTINGS, applyTheme } = await import("../store/useStore");
  const { api } = await import("../lib/api");
  const { default: AgendaPage } = await import("../components/AgendaPage");
  const { default: WeekView } = await import("../components/WeekView");
  const { ROUTINE_SLOTS } = await import("../domain/routine");
  const h = React.createElement;
  const root = createRoot(document.getElementById("root")!);
  const act = async (fn: () => void | Promise<void>) => React.act(async () => { await fn(); await sleep(30); });
  const st = () => useStore.getState();
  localStorage.clear();
  await act(async () => { await st().init(); applyTheme(DEFAULT_SETTINGS); });
  for (const i of st().agendaItems) await api.deleteAgendaItem(i.id);
  await act(async () => {
    await st().reloadAgenda();
    await st().saveAgendaItem({ title: "第一张便签", pinned: true });
    await st().saveAgendaItem({ title: "第二张便签" });
    root.render(h(AgendaPage));
  });
  const card = (title: string) => qa(".ag-card").find((e) => text(e.querySelector(".ag-title") as HTMLElement) === title)!;
  const first = st().agendaItems.find((i) => i.title === "第一张便签")!;
  const second = st().agendaItems.find((i) => i.title === "第二张便签")!;
  const firstButton = (label: string) => Array.from(card("第一张便签").querySelectorAll("button")).find((e) => text(e) === label)!;
  const writeNote = async (value: string) => act(() => {
    const el = q(".ag-note-input") as HTMLTextAreaElement;
    Object.getOwnPropertyDescriptor(window.HTMLTextAreaElement.prototype, "value")!.set!.call(el, value);
    el.dispatchEvent(new window.Event("input", { bubbles: true }));
  });
  section("v1.3 便签分区与明显入口");
  ok("两张便签各有正文和待办分区", qa('.ag-note-section[aria-label="正文"]').length === 2 && qa('.ag-task-section[aria-label="待办"]').length === 2);
  ok("无需展开即可看到添加待办与添加文字", !!firstButton("添加待办") && !!firstButton("添加文字"));
  ok("不显示七天事件预览", !q(".ag-upcoming"));
  await act(() => click(firstButton("添加待办")));
  ok("添加待办入口展开并聚焦输入", !!card("第一张便签").querySelector(".ms-input") && document.activeElement === card("第一张便签").querySelector(".ms-input"));
  await act(() => typeInto(card("第一张便签").querySelector(".ms-input"), "检查实验数据"));
  await act(() => pressKey(card("第一张便签").querySelector(".ms-input"), "Enter", { composing: true }));
  ok("待办 IME 回车不提交", !st().agendaSubitems.some((i) => i.itemId === first.id));
  await act(() => pressKey(card("第一张便签").querySelector(".ms-input"), "Enter"));
  ok("待办回车保存并保持展开", st().agendaSubitems.some((i) => i.title === "检查实验数据") && st().agendaExpandedIds.includes(first.id));
  await act(() => click(Array.from(card("第二张便签").querySelectorAll("button")).find((e) => text(e) === "添加待办")!));
  ok("两张便签可以同时展开", st().agendaExpandedIds.includes(first.id) && st().agendaExpandedIds.includes(second.id));
  await act(() => click(firstButton("添加文字")));
  await writeNote("一段正文\n第二行说明");
  await act(() => pressKey(q(".ag-note-input"), "Enter"));
  ok("正文 Enter 不保存", st().agendaItems.find((i) => i.id === first.id)?.note === null && !!q(".ag-note-input"));
  await act(() => root.render(h("div", null, "日历占位")));
  await act(() => root.render(h(AgendaPage)));
  ok("切页后未保存正文草稿仍在", (q(".ag-note-input") as HTMLTextAreaElement).value === "一段正文\n第二行说明");
  const saveNote = api.saveAgendaNote;
  api.saveAgendaNote = async () => { throw new Error("测试保存失败"); };
  await act(() => click(firstButton("保存文字")));
  ok("正文保存失败保留草稿并显示错误", !!q(".ag-note-input") && text(q('[role="alert"]')).includes("测试保存失败"));
  api.saveAgendaNote = saveNote;
  await act(() => click(firstButton("保存文字")));
  ok("正文保存后可读且不丢置顶和待办", text(card("第一张便签").querySelector(".ag-note")) === "一段正文\n第二行说明" && st().agendaItems.find((i) => i.id === first.id)!.pinned && st().agendaSubitems.length === 1);
  await act(() => click(firstButton("编辑文字")));
  await writeNote("不该保存的改动");
  await act(() => click(firstButton("取消")));
  ok("取消正文编辑保持原文", st().agendaItems.find((i) => i.id === first.id)!.note === "一段正文\n第二行说明");
  await act(() => click(card("第一张便签").querySelector(".ms-check")));
  await act(async () => { await st().duplicateAgendaItem(first.id); });
  const copy = st().agendaItems.find((i) => i.title === "第一张便签 副本")!;
  ok("复制包含正文且重置置顶归档", copy.note === "一段正文\n第二行说明" && !copy.pinned && !copy.archived);
  ok("复制包含完成的待办且生成新 ID", st().agendaSubitems.some((i) => i.itemId === copy.id && i.done && i.id !== st().agendaSubitems.find((x) => x.itemId === first.id)!.id));
  await act(async () => { await st().scheduleAgendaItem(first.id, "2026-10-04"); });
  const scheduled = st().events.find((e) => e.title === first.title)!;
  ok("安排到某天保留正文、归档便签并不复制已完成待办", scheduled.allDay && scheduled.note!.includes("第二行说明") && !scheduled.note!.includes("检查实验数据") && st().agendaItems.find((i) => i.id === first.id)!.archived);

  section("v1.3 日视图双栏与固定时段");
  const date = "2026-10-02";
  for (const slot of ROUTINE_SLOTS) await api.clearRoutineSlot(date, slot.key);
  await act(() => { st().goto(date); root.render(h(WeekView, { mode: "day" })); });
  ok("保留内部月历", !!q(".rail .mini-cal"));
  ok("左右栏标题正确", text(q(".day-column-titles")) === "日常安排事件");
  ok("同一时间轴容器有两个平行内容栏", q(".day-two-cols")?.children.length === 2 && !!q(".day-two-cols > .routine-col") && !!q(".day-two-cols > .tg-col:not(.routine-col)"));
  ok("初始四个空虚框", qa(".routine-block.is-empty").length === 4);
  ok("块内不重复显示时间", qa(".routine-block").every((e) => !text(e).includes(":")));
  ok("四块按分钟与时间轴对齐", qa(".routine-block").every((e, i) => Math.abs(parseFloat(e.style.top) - ROUTINE_SLOTS[i].start / 60 * 44) < 0.01 && Math.abs(parseFloat(e.style.height) - (ROUTINE_SLOTS[i].end - ROUTINE_SLOTS[i].start) / 60 * 44) < 0.01));
  ok("浏览空日期不插入安排", (await api.listRoutineSlots(date)).length === 0);
  await act(async () => {
    await api.saveEvent({ title: "并发事件甲", startDate: date, endDate: date, allDay: false, startTime: "09:00", endTime: "10:00" });
    await api.saveEvent({ title: "并发事件乙", startDate: date, endDate: date, allDay: false, startTime: "09:30", endTime: "10:30" });
    await api.saveEvent({ title: "全天甲", startDate: date, endDate: date, allDay: true });
    await api.saveEvent({ title: "全天乙", startDate: date, endDate: date, allDay: true });
    await st().reloadEvents();
  });
  ok("并发事件在右栏泳道显示，不侵入日常栏", qa(".day-two-cols > .tg-col:not(.routine-col) .ev-block").length >= 2 && !q(".routine-col .ev-block"));
  ok("多个全天事件各有一行，不相互覆盖", qa(".tg-allday .allday-bar").length >= 2 && new Set(qa(".tg-allday .allday-bar").map((e) => e.parentElement)).size === qa(".tg-allday .allday-bar").length);
  await act(() => click(qa(".ev-block").find((e) => text(e).includes("并发事件甲"))!));
  ok("右栏点击事件仍打开事件编辑", st().eventDraft?.title === "并发事件甲");
  await act(() => {
    st().openEventDraft(null);
    q(".tg-scroll")!.scrollTop = 350;
    q(".day-two-cols > .tg-col:not(.routine-col)")!.dispatchEvent(new window.MouseEvent("dblclick", { bubbles: true, clientY: 14.5 * 44 }));
  });
  ok("滚动后双击新建时间不重复加滚动偏移，结束正确加一小时", st().eventDraft?.startTime === "14:30" && st().eventDraft?.endTime === "15:30");
  await act(() => st().openEventDraft(null));
  const open = () => click(q('[data-slot="morning_1"]'));
  await act(open);
  ok("类别浮层在 body 下，含六个建议", !!document.body.querySelector(".routine-pop") && qa(".routine-options button").length === 6);
  await act(() => click(byText(".routine-options button", "英语")));
  ok("选择建议不会提前保存", (await api.listRoutineSlots(date)).length === 0);
  await act(() => click(byText(".routine-pop-actions button", "保存类别")));
  ok("保存后显示类别并关闭浮层", text(q('[data-slot="morning_1"]')) === "英语" && !q(".routine-pop"));
  const evCount = st().events.length;
  await act(open);
  await act(() => typeInto(q('.routine-label input'), "新的研究方向"));
  await act(() => click(byText(".routine-pop-actions button", "保存类别")));
  ok("支持自定义类别且不生成事件", (await api.listRoutineSlots(date))[0].category === "新的研究方向" && st().events.length === evCount);
  await act(() => st().goto("2026-10-03"));
  ok("切到次日恢复四个空块", qa(".routine-block.is-empty").length === 4);
  await act(() => st().goto(date));
  ok("返回原日保留类别", text(q('[data-slot="morning_1"]')) === "新的研究方向");
  const oldSave = api.saveRoutineSlot;
  api.saveRoutineSlot = async () => { throw new Error("类别保存失败"); };
  await act(open);
  await act(() => typeInto(q('.routine-label input'), "失败草稿"));
  await act(() => click(byText(".routine-pop-actions button", "保存类别")));
  ok("类别失败保留原块和输入并提示", text(q('[data-slot="morning_1"]')) === "新的研究方向" && (q('.routine-label input') as HTMLInputElement).value === "失败草稿" && text(q('.routine-pop [role="alert"]')).includes("类别保存失败"));
  api.saveRoutineSlot = oldSave;
  await act(() => pressKey(q('.routine-label input'), "Escape"));
  ok("Esc 取消不改原类别", !q(".routine-pop") && (await api.listRoutineSlots(date))[0].category === "新的研究方向");
  await act(open);
  await act(() => click(byText(".routine-pop-actions button", "清空类别")));
  ok("清空恢复虚框且删除已填记录", qa(".routine-block.is-empty").length === 4 && (await api.listRoutineSlots(date)).length === 0);
  await act(() => {
    st().updateSetting("fontSize", "xl");
  });
  ok("特大字号下时间块同步行高", Math.abs(parseFloat(q('[data-slot="morning_2"]')!.style.top) - 10.25 * 57) < 0.01);
  const oldList = api.listRoutineSlots;
  let resolveOld: ((rows: Awaited<ReturnType<typeof oldList>>) => void) | undefined;
  api.listRoutineSlots = (d) => d === "2026-10-05" ? new Promise((resolve) => { resolveOld = resolve; }) : oldList(d);
  await act(() => st().goto("2026-10-05"));
  await act(() => st().goto("2026-10-06"));
  await act(() => resolveOld!([{ date: "2026-10-05", slotKey: "morning_1", category: "旧日期迟到响应", createdAt: "", updatedAt: "" }]));
  ok("快速切日期不被旧查询响应覆盖", qa(".routine-block.is-empty").length === 4 && !text(q(".routine-col")).includes("旧日期迟到响应"));
  api.listRoutineSlots = oldList;
  api.listRoutineSlots = async () => { throw new Error("读取安排失败"); };
  await act(() => st().goto("2026-10-07"));
  ok("查询失败时空块禁用且提供重试", qa(".routine-block").every((e) => (e as HTMLButtonElement).disabled) && !!byText(".routine-status button", "重试"));
  api.listRoutineSlots = oldList;
  await act(() => click(byText(".routine-status button", "重试")));
  ok("重试成功可编辑且不写入空记录", qa(".routine-block").every((e) => !(e as HTMLButtonElement).disabled) && (await api.listRoutineSlots("2026-10-07")).length === 0);
  await act(() => root.render(h(WeekView, { mode: "week" })));
  ok("周视图保留七列且不显示日常块", qa(".tg-cols > .tg-col").length === 7 && !q(".routine-block"));
  report();
}
main().catch((e) => { console.error(e); process.exit(1); });
